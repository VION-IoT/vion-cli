using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Vion.Cli.Derive
{
    /// <summary>
    ///     Writes the derived model as the C# table the tool compiles in: data only, constructing the records
    ///     <c>Vion.Cli/Derived/Operation.cs</c> declares by hand, so that the emitter never carries behaviour.
    /// </summary>
    internal static class Emitter
    {
        public static string Emit(DerivedDocument document)
        {
            var sb = new StringBuilder();
            sb.Append("// <auto-generated>\n");
            sb.Append("//     Generated by Vion.Cli.Derive from openapi/v1.json (sha256 ").Append(document.SnapshotSha256).Append(") and cli.json.\n");
            sb.Append("//     Do not edit; run scripts/derive.ps1. The diff of this file is the review of an API move.\n");
            sb.Append("// </auto-generated>\n\n");
            sb.Append("using System.Collections.Generic;\n\n");
            sb.Append("namespace Vion.Cli.Derived;\n\n");
            sb.Append("internal static partial class Operations\n{\n");
            sb.Append("    public const string SnapshotSha256 = ").Append(Literal(document.SnapshotSha256)).Append(";\n\n");
            sb.Append("    public const string ApiVersion = ").Append(Literal(document.ApiVersion)).Append(";\n\n");
            sb.Append("    public static readonly IReadOnlyList<string> GlobalOptionNames = new[] { ")
              .Append(string.Join(", ", Naming.GlobalOptionNames.Select(Literal)))
              .Append(" };\n\n");
            sb.Append("    public static readonly IReadOnlyList<Operation> All = new Operation[]\n    {\n");
            foreach (var operation in document.Operations)
            {
                EmitOperation(sb, operation);
            }

            sb.Append("    };\n}\n");
            return sb.ToString();
        }

        private static void EmitOperation(StringBuilder sb, DerivedOperation o)
        {
            sb.Append("        new Operation(\n");
            sb.Append("            ")
              .Append(Literal(o.Id))
              .Append(", ")
              .Append(Literal(o.Domain))
              .Append(", ")
              .Append(Literal(o.Aggregate))
              .Append(", ")
              .Append(Literal(o.Verb))
              .Append(",\n");
            sb.Append("            ").Append(Literal(o.CommandDomain)).Append(", ").Append(Literal(o.CommandAggregate)).Append(", ").Append(Literal(o.CommandVerb)).Append(",\n");
            sb.Append("            ").Append(Literal(o.Method)).Append(", ").Append(Literal(o.Template)).Append(",\n");
            sb.Append("            ").Append(Literal(o.Description)).Append(",\n");
            if (o.Parameters.Count == 0)
            {
                sb.Append("            new Parameter[0],\n");
            }
            else
            {
                sb.Append("            new[]\n            {\n");
                foreach (var p in o.Parameters)
                {
                    sb.Append("                new Parameter(")
                      .Append(Literal(p.Name))
                      .Append(", ")
                      .Append(Literal(p.OptionName))
                      .Append(", ")
                      .Append(Literal(p.Global))
                      .Append(", ")
                      .Append("ParameterLocation.")
                      .Append(p.In)
                      .Append(", ")
                      .Append(Bool(p.Required))
                      .Append(", ")
                      .Append("ParameterKind.")
                      .Append(p.Kind)
                      .Append(", ")
                      .Append(Literal(p.Description))
                      .Append("),\n");
                }

                sb.Append("            },\n");
            }

            if (o.Body == null)
            {
                sb.Append("            null,\n");
            }
            else
            {
                sb.Append("            new Body(")
                  .Append(Literal(o.Body.ContentType))
                  .Append(", ")
                  .Append(Literal(o.Body.SchemaName))
                  .Append(", ")
                  .Append(Literal(o.Body.FilePart))
                  .Append(", ")
                  .Append(StringArray(o.Body.TextParts))
                  .Append("),\n");
            }

            sb.Append("            Effect.")
              .Append(o.Effect)
              .Append(", ")
              .Append(Bool(o.Idempotent))
              .Append(", ")
              .Append(Bool(o.Versioned))
              .Append(", ")
              .Append(Bool(o.DryRun))
              .Append(", ")
              .Append(Bool(o.Deprecated))
              .Append(",\n");
            sb.Append("            new Authorization(")
              .Append(Literal(o.Authorization.Mode))
              .Append(", ")
              .Append(StringArray(o.Authorization.Permissions))
              .Append(", ")
              .Append(Literal(o.Authorization.ScopeType))
              .Append(", ")
              .Append(Literal(o.Authorization.ScopeFrom))
              .Append("),\n");
            sb.Append("            ").Append(Bool(o.Hidden)).Append(", ").Append(Literal(o.Alias)).Append("),\n");
        }

        private static string StringArray(IReadOnlyList<string> values)
        {
            return values.Count == 0 ? "new string[0]" : "new[] { " + string.Join(", ", values.Select(Literal)) + " }";
        }

        private static string Bool(bool value)
        {
            return value ? "true" : "false";
        }

        /// <summary>
        ///     A C# string literal, or <c>null</c>; every character outside the printable ASCII range is escaped so the file
        ///     is ASCII whatever the document carries.
        /// </summary>
        private static string Literal(string? value)
        {
            if (value == null)
            {
                return "null";
            }

            var sb = new StringBuilder(value.Length + 2);
            sb.Append('"');
            foreach (var c in value)
            {
                switch (c)
                {
                    case '"':
                        sb.Append("\\\"");
                        break;
                    case '\\':
                        sb.Append("\\\\");
                        break;
                    case '\n':
                        sb.Append("\\n");
                        break;
                    case '\r':
                        sb.Append("\\r");
                        break;
                    case '\t':
                        sb.Append("\\t");
                        break;
                    default:
                        if (c < 0x20 || c > 0x7e)
                        {
                            sb.Append("\\u").Append(((int)c).ToString("x4", System.Globalization.CultureInfo.InvariantCulture));
                        }
                        else
                        {
                            sb.Append(c);
                        }

                        break;
                }
            }

            sb.Append('"');
            return sb.ToString();
        }
    }
}