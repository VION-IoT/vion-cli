using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Vion.Cli.Derive
{
    /// <summary>
    ///     Writes the derived channels as the C# table the tool compiles in: data only, constructing the records
    ///     <c>Vion.Cli/Derived/Channel.cs</c> declares by hand.
    /// </summary>
    internal static class ChannelEmitter
    {
        public static string Emit(DerivedChannels document)
        {
            var sb = new StringBuilder();
            sb.Append("// <auto-generated>\n");
            sb.Append("//     Generated by Vion.Cli.Derive from asyncapi/v1.json (sha256 ").Append(document.SnapshotSha256).Append(") and openapi/v1.json.\n");
            sb.Append("//     Do not edit; run scripts/derive.ps1. The diff of this file is the review of a move of the event document.\n");
            sb.Append("// </auto-generated>\n\n");
            sb.Append("using System.Collections.Generic;\n\n");
            sb.Append("namespace Vion.Cli.Derived;\n\n");
            sb.Append("internal static partial class Channels\n{\n");
            sb.Append("    public const string SnapshotSha256 = ").Append(Emitter.Literal(document.SnapshotSha256)).Append(";\n\n");
            sb.Append("    public static readonly IReadOnlyList<Channel> All = new Channel[]\n    {\n");
            foreach (var channel in document.Channels)
            {
                EmitChannel(sb, channel);
            }

            sb.Append("    };\n}\n");
            return sb.ToString();
        }

        private static void EmitChannel(StringBuilder sb, DerivedChannel c)
        {
            sb.Append("        new Channel(\n");
            sb.Append("            ").Append(Emitter.Literal(c.Id)).Append(", ").Append(Emitter.Literal(c.CommandDomain)).Append(", ").Append(Emitter.Literal(c.CommandAggregate)).Append(",\n");
            sb.Append("            ").Append(Emitter.Literal(c.Description)).Append(",\n");
            sb.Append("            ").Append(Emitter.Literal(c.MessageName)).Append(",\n");
            if (c.Parameters.Count == 0)
            {
                sb.Append("            new ChannelParameter[0],\n");
            }
            else
            {
                sb.Append("            new[]\n            {\n");
                foreach (var p in c.Parameters)
                {
                    sb.Append("                new ChannelParameter(")
                      .Append(Emitter.Literal(p.Name))
                      .Append(", ")
                      .Append(Emitter.Literal(p.OptionName))
                      .Append(", ")
                      .Append(Emitter.Literal(p.Global))
                      .Append(", ")
                      .Append(Emitter.Bool(p.Required))
                      .Append(", ")
                      .Append(Emitter.Literal(p.Description))
                      .Append("),\n");
                }

                sb.Append("            },\n");
            }

            sb.Append("            new[]\n            {\n");
            foreach (var h in c.HandOuts)
            {
                sb.Append("                new HandOut(")
                  .Append(Emitter.Literal(h.Key))
                  .Append(", ")
                  .Append(Emitter.Literal(h.Operation))
                  .Append(", ")
                  .Append(Emitter.Literal(h.Row))
                  .Append(", ")
                  .Append(Joins(h.Joins))
                  .Append(", ")
                  .Append(Emitter.StringArray(h.Selects))
                  .Append("),\n");
            }

            sb.Append("            },\n");
            if (c.Registration == null)
            {
                sb.Append("            null),\n");
                return;
            }

            var r = c.Registration;
            sb.Append("            new Registration(").Append(Emitter.Literal(r.Operation)).Append(", ").Append(Emitter.Literal(r.SubscriberIdMember)).Append(",\n");
            sb.Append("                new[]\n                {\n");
            foreach (var f in r.Fills)
            {
                sb.Append("                    new Fill(")
                  .Append(Emitter.Literal(f.ChannelParameter))
                  .Append(", ")
                  .Append(Emitter.Bool(f.FromInput))
                  .Append(", ")
                  .Append(Emitter.Literal(f.OperationParameter))
                  .Append(", ")
                  .Append(Emitter.Literal(f.BodyMember))
                  .Append("),\n");
            }

            sb.Append("                },\n");
            sb.Append("                ").Append(Emitter.Literal(r.InputOptionName)).Append(", ").Append(Emitter.Literal(r.InputRowMember)).Append(")),\n");
        }

        private static string Joins(IReadOnlyList<DerivedJoin> joins)
        {
            return joins.Count == 0 ? "new Join[0]" :
                       "new[] { " +
                       string.Join(", ", joins.Select(j => $"new Join({Emitter.Literal(j.ChannelParameter)}, {Emitter.Literal(j.OperationParameter)}, {Emitter.Literal(j.Member)})")) +
                       " }";
        }
    }
}
